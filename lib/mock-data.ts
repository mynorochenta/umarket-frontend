export const publicacionesDestacadas = publicaciones.filter((p) => p.destacada);

export function getPublicacion(id: string): Publicacion | undefined {
  return publicaciones.find((p) => p.id === id);
}

export function getUsuario(id: string): Usuario | undefined {
  return usuarios.find((u) => u.id === id);
}

export function getPublicacionesPorVendedor(vendedorId: string): Publicacion[] {
  return publicaciones.filter((p) => p.vendedor.id === vendedorId && p.activa);
}

export function getResenasPorDestinatario(destinatarioId: string): Resena[] {
  return resenas.filter((r) => r.destinatarioId === destinatarioId);
}

export function getConversacionesPorUsuario(usuarioId: string): Conversacion[] {
  return conversaciones.filter((c) => c.participantes.includes(usuarioId));
}
